#!/bin/sh
# Проверяет, что режим шары согласован с режимом монтирования тома.
#
# Режим записи задан в двух местах, и они обязаны совпадать:
#
#   * `verify-mounts.sh` — режим, с которым том смонтирован на хосте;
#   * `smb.conf`, `read only` — что Samba разрешает клиенту.
#
# Расхождение даёт отказ, который не читается со стороны клиента: том смонтирован
# на запись, режим в проверке — `rw`, под поднимается, но `read only = yes` в
# секции шары заставляет клиента получать ошибку записи. Так уже случилось при
# переводе ntfs1 на запись: том, проверка и манифест были обновлены, а секция
# шары осталась `read only = yes`.
#
# Раньше это правило проверялось задачей роли `ntfs_samba`; роль перестала
# управлять конфигом шар, и проверка переехала сюда.
set -eu

root="$(cd "$(dirname "$0")/.." && pwd)"
conf="$root/manifests/config/smb.conf"
check="$root/manifests/config/verify-mounts.sh"

fail() { echo "тест: $*" >&2; exit 1; }

# Ожидаемое: режим тома → что должна разрешать шара.
expected="$(sed -n '/^SHARES="/,/"/p' "$check" | tr -d '"' | sed 's/^SHARES=//' |
  awk 'NF >= 2 && $1 ~ /^ntfs[0-9]+$/ { print $1, ($2 == "rw" ? "no" : "yes") }' | sort)"

# Фактическое: `read only` в каждой секции шары.
actual="$(awk '
  /^\[/ { name = $0; sub(/^\[/, "", name); sub(/\]$/, "", name); next }
  name ~ /^ntfs/ && $1 == "read" && $2 == "only" && $3 == "=" { print name, $4; name = "" }
' "$conf" | sort)"

[ -n "$expected" ] || fail "не удалось прочитать режимы томов из verify-mounts.sh"
[ -n "$actual" ] || fail "не удалось прочитать read only из smb.conf"

if [ "$expected" != "$actual" ]; then
  echo "тест: режим шар разошёлся с режимом монтирования" >&2
  echo "тест: ожидалось (том → read only):" >&2
  printf '%s\n' "$expected" | sed 's/^/  /' >&2
  echo "тест: в smb.conf:" >&2
  printf '%s\n' "$actual" | sed 's/^/  /' >&2
  exit 1
fi

echo "тест: режимы шар совпадают с монтированием"
